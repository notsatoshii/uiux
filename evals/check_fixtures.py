#!/usr/bin/env python3
"""Confirm the uiux eval fixtures' planted defects without running Claude.

Usage: python evals/check_fixtures.py [--build] [--json]

For each case folder in evals/ that has workspace/docs/design/<slug>/brief.md it:
  1. runs a small static check (stdlib only) on workspace/<slug>/index.html and styles.css plus the
     house rules in workspace/uiux.md, and checks that the defects it finds are exactly the planted
     ones (the control must be clean, and no fixture may carry a defect by accident):
       contrast         a CSS rule whose color/background pair is under 4.5:1
       unnamed-control  a <button> or <a> with no text, aria-label, aria-labelledby or title
       img-no-alt       an <img> with no alt attribute
       overflow         a fixed width or min-width over 375px (the phone viewport)
       tap-target       a button, chip or link class with height or min-height under 44px
       forbidden-word   a word from uiux.md "forbidden words:" in the page text
       unsourced-number a percentage or a 2+ digit number in the page text that the brief does not carry
  2. checks that scaffold.sh matches workspace/ (--build rewrites it from workspace/);
  3. runs every regex grader against a sample finding line it should match, and planted graders
     against the control sample they must not match;
  4. checks trigger-queries.json (20 queries, 8 to 12 of each kind, no duplicates).
Exit 0 when every expectation holds, 1 otherwise.

The static check is a fixture guard, not a critic: it proves the defect is in the files, so a
missed finding in a real run is the critic's miss, not a broken fixture.
"""
import argparse
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

EVALS = Path(__file__).resolve().parent
DELIM = "UIUX_FIXTURE_EOF"
PHONE_W = 375
MIN_TAP = 44
MIN_CONTRAST = 4.5

# The exact set of static-check rules each case must trip (empty set = clean).
EXPECT = {
    "planted-contrast-iconbutton": {"contrast", "unnamed-control"},
    "planted-invented-proof": {"forbidden-word", "unsourced-number"},
    "planted-overflow-tap": {"overflow", "tap-target"},
    "control-clean": set(),
}

# Finding lines in the cycle report's format (templates/cycle-report.md):
# "- [sev] [critic] element · issue → what was done (file:line)".
SAMPLE_REPORT = {
    "planted-contrast-iconbutton": "- [1] [01] .lede · body text contrast 2.5:1 under 4.5:1 → ink set to --muted (styles.css:19)\n"
                                   "- [1] [01] header menu icon button · no accessible name → aria-label added (index.html:13)\n",
    "planted-invented-proof": "- [1] [03] hero .lede · 94% statistic is invented, brief has no numbers → needs data: source (index.html:16)\n"
                              "- [1] [03] hero .lede · Guaranteed is a forbidden word in uiux.md → removed (index.html:16)\n",
    "planted-overflow-tap": "- [1] [01] .plans · fixed 520px width causes horizontal scroll at 375 → width removed (styles.css:24)\n"
                            "- [2] [01, 04] .chip filters · tap target 28px under 44px → min-height 44px (styles.css:22)\n",
    "control-clean": "- [2] [05] hero · headline and lede sit close; more air above the button → spacing (styles.css:17)\n"
                     "- [3] [09] .plan cards · border and radius differ from steps by a hair → shared token\n",
}


def build_scaffold(workspace):
    files = sorted(f for f in workspace.rglob("*") if f.is_file())
    out = [
        "#!/usr/bin/env bash",
        "# Generated by evals/check_fixtures.py --build from workspace/. Edit workspace/, then rebuild.",
        "# Writes the fixture into the eval run's empty workspace (claude plugin eval ... --scaffold).",
        "set -euo pipefail",
    ]
    for d in sorted({f.parent.relative_to(workspace).as_posix() for f in files} - {"."}):
        out.append(f"mkdir -p '{d}'")
    for f in files:
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n")
        if DELIM in text:
            raise SystemExit(f"{f}: contains the heredoc delimiter {DELIM}")
        out.append(f"cat > '{f.relative_to(workspace).as_posix()}' <<'{DELIM}'")
        out.append(text[:-1] if text.endswith("\n") else text)
        out.append(DELIM)
    return "\n".join(out) + "\n"


# ---------- static check ----------

def hex_rgb(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))


def luminance(rgb):
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    la, lb = sorted((luminance(hex_rgb(a)), luminance(hex_rgb(b))), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def css_rules(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        decls = {}
        for d in body.split(";"):
            if ":" in d:
                k, v = d.split(":", 1)
                decls[k.strip().lower()] = v.strip()
        yield sel.strip(), decls


def resolve(v, props):
    m = re.fullmatch(r"var\((--[\w-]+)\)", v or "")
    v = props.get(m.group(1)) if m else v
    return v if v and re.fullmatch(r"#[0-9a-fA-F]{3}(?:[0-9a-fA-F]{3})?", v) else None


class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack, self.controls, self.imgs, self.text = [], [], [], []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "title"):
            self.skip += 1
        if tag == "img":
            self.imgs.append(a)
        if tag in ("button", "a"):
            self.stack.append({"tag": tag, "attrs": a, "text": ""})

    def handle_endtag(self, tag):
        if tag in ("script", "style", "title"):
            self.skip -= 1
        if tag in ("button", "a") and self.stack:
            self.controls.append(self.stack.pop())

    def handle_data(self, data):
        if self.skip:
            return
        self.text.append(data)
        for c in self.stack:
            c["text"] += data


def static_check(ws, slug):
    hits = []
    surf = ws / slug
    css = (surf / "styles.css").read_text(encoding="utf-8")
    rules = list(css_rules(css))
    props = {k: v for sel, d in rules if sel == ":root" for k, v in d.items() if k.startswith("--")}
    for sel, d in rules:
        fg = resolve(d.get("color"), props)
        bg = resolve(d.get("background-color") or d.get("background"), props)
        if fg and bg and contrast(fg, bg) < MIN_CONTRAST:
            hits.append(("contrast", f"{sel}: {fg} on {bg} = {contrast(fg, bg):.2f}:1"))
        for k in ("width", "min-width"):
            m = re.fullmatch(r"(\d+)px", d.get(k, ""))
            if m and int(m.group(1)) > PHONE_W:
                hits.append(("overflow", f"{sel}: {k} {m.group(0)} > {PHONE_W}px"))
        if re.search(r"\b(?:button|a)\b|\.(?:btn|chip|icon-btn)\b", sel):
            for k in ("height", "min-height"):
                m = re.fullmatch(r"(\d+)px", d.get(k, ""))
                if m and int(m.group(1)) < MIN_TAP:
                    hits.append(("tap-target", f"{sel}: {k} {m.group(0)} < {MIN_TAP}px"))
    page = Page()
    page.feed((surf / "index.html").read_text(encoding="utf-8"))
    for c in page.controls:
        a = c["attrs"]
        if not c["text"].strip() and not any(a.get(k) for k in ("aria-label", "aria-labelledby", "title")):
            hits.append(("unnamed-control", f"<{c['tag']} class=\"{a.get('class', '')}\"> has no accessible name"))
    for a in page.imgs:
        if "alt" not in a:
            hits.append(("img-no-alt", f"<img src=\"{a.get('src', '')}\">"))
    text = " ".join(" ".join(page.text).split())
    house = (ws / "uiux.md").read_text(encoding="utf-8") if (ws / "uiux.md").exists() else ""
    m = re.search(r"^-?\s*forbidden words:\s*(.+)$", house, re.M | re.I)
    for w in [x.strip() for x in m.group(1).split(",")] if m else []:
        if w and re.search(rf"\b{re.escape(w)}\b", text, re.I):
            hits.append(("forbidden-word", f"'{w}' in page text"))
    brief = (ws / "docs" / "design" / slug / "brief.md").read_text(encoding="utf-8")
    for n in sorted(set(re.findall(r"\d[\d,.]*\s*%|\b\d{2,}\b", text))):
        if n not in brief:
            hits.append(("unsourced-number", f"'{n}' in page text, not in the brief"))
    return hits


def check_case(case_dir, build):
    name = case_dir.name
    ws = case_dir / "workspace"
    res = {"case": name, "ok": True, "lines": []}

    def bad(msg):
        res["ok"] = False
        res["lines"].append(f"  FAIL {msg}")

    def good(msg):
        res["lines"].append(f"  ok   {msg}")

    exp = EXPECT.get(name)
    briefs = sorted(ws.glob("docs/design/*/brief.md"))
    if exp is None:
        bad("no expectations in check_fixtures.EXPECT")
        return res
    if len(briefs) != 1:
        bad(f"expected one workspace/docs/design/<slug>/brief.md (--skip-interview needs it), found {len(briefs)}")
        return res
    slug = briefs[0].parent.name
    if not (ws / slug / "index.html").exists():
        bad(f"no workspace/{slug}/index.html beside the brief")
        return res
    prompt = (case_dir / "prompt.md").read_text(encoding="utf-8")
    if f"/uiux {slug}/index.html" not in prompt or "--skip-interview" not in prompt:
        bad(f"prompt.md does not run /uiux {slug}/index.html --skip-interview")
    hits = static_check(ws, slug)
    got = {r for r, _ in hits}
    if got == exp:
        good("static check: " + ("clean" if not hits else "; ".join(f"[{r}] {d}" for r, d in hits)))
    else:
        bad(f"static check expected {sorted(exp) or 'clean'}, got: " + ("; ".join(f"[{r}] {d}" for r, d in hits) or "clean"))

    want = build_scaffold(ws)
    sc = case_dir / "scaffold.sh"
    if build:
        sc.write_bytes(want.encode("utf-8"))
        good("scaffold.sh rebuilt from workspace/")
    elif not sc.exists():
        bad("scaffold.sh missing; run with --build")
    elif sc.read_bytes().decode("utf-8") != want:
        bad("scaffold.sh is stale; run with --build")
    else:
        good("scaffold.sh matches workspace/")
    return res


def grader_fields(text):
    fm = text.split("---", 2)[1] if text.startswith("---") else ""
    get = lambda k: (re.search(rf"^{k}:\s*(.*)$", fm, re.M) or [None, None])[1]
    pat = get("pattern")
    if pat and pat.startswith("'") and pat.endswith("'"):
        pat = pat[1:-1].replace("''", "'")
    path = re.search(r"^\s+path:\s*(.+)$", fm, re.M)
    return {"type": get("type"), "pattern": pat, "flags": get("flags") or "", "match": get("match"),
            "path": path.group(1).strip() if path else get("path")}


def check_graders(cases):
    lines, ok = [], True
    for case_dir in cases:
        for g in sorted((case_dir / "graders").glob("*.md")):
            f = grader_fields(g.read_text(encoding="utf-8"))
            if f["type"] != "regex":
                continue
            fl = (re.M if "m" in f["flags"] else 0) | (re.I if "i" in f["flags"] else 0)
            sample = SAMPLE_REPORT.get(case_dir.name, "")
            hit = re.search(f["pattern"], sample, fl) is not None
            passed = (not hit) if f["match"] == "not_contains" else hit
            neg = False
            if f["match"] != "not_contains" and case_dir.name != "control-clean":
                neg = re.search(f["pattern"], SAMPLE_REPORT["control-clean"], fl) is not None
            if passed and not neg:
                continue
            ok = False
            lines.append(f"  FAIL {case_dir.name}/graders/{g.name}: " + ("matches the control sample" if neg else "does not match its sample"))
    n = sum(1 for c in cases for _ in (c / "graders").glob("*.md"))
    lines.insert(0, f"  {'ok  ' if ok else 'FAIL'} regex graders behave on sample findings ({n} graders in {len(cases)} cases)")
    return ok, lines


def check_triggers():
    p = EVALS / "trigger-queries.json"
    if not p.exists():
        return False, ["  FAIL trigger-queries.json missing"]
    items = json.loads(p.read_text(encoding="utf-8"))
    pos = sum(1 for i in items if i.get("should_trigger") is True)
    neg = sum(1 for i in items if i.get("should_trigger") is False)
    dup = len(items) - len({i["query"] for i in items})
    ok = len(items) == 20 and 8 <= pos <= 12 and 8 <= neg <= 12 and dup == 0
    return ok, [f"  {'ok  ' if ok else 'FAIL'} trigger-queries.json: {len(items)} queries, {pos} should trigger, {neg} should not, {dup} duplicates"]


def main():
    ap = argparse.ArgumentParser(description="Check the uiux eval fixtures with a static check only.")
    ap.add_argument("--build", action="store_true", help="rewrite each case's scaffold.sh from its workspace/")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    cases = sorted(d for d in EVALS.iterdir() if (d / "workspace").is_dir() and (d / "prompt.md").exists())
    results = [check_case(d, a.build) for d in cases]
    gok, glines = check_graders(cases)
    tok, tlines = check_triggers()
    all_ok = bool(cases) and all(r["ok"] for r in results) and gok and tok
    if a.json:
        out = json.dumps({"ok": all_ok, "cases": results, "graders": glines, "triggers": tlines}, ensure_ascii=False, indent=1)
    else:
        lines = []
        for r in results:
            lines.append(f"{'PASS' if r['ok'] else 'FAIL'} {r['case']}")
            lines += r["lines"]
        lines += [f"{'PASS' if gok else 'FAIL'} graders"] + glines + [f"{'PASS' if tok else 'FAIL'} triggers"] + tlines
        lines.append("all fixtures as planted" if all_ok else "some expectations failed")
        out = "\n".join(lines)
    sys.stdout.buffer.write((out + "\n").encode("utf-8"))
    sys.exit(0 if all_ok else 1)


if __name__ == "__main__":
    main()
